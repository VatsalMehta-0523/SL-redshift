# =============================================================================
# 02_inspect_clean.R — Workflow steps 2–3: inspect, clean, preprocess, import
# Inputs : data/raw/sdss_raw.csv
# Outputs: data/processed/sdss_clean.csv (exactly 100 rows),
#          outputs/tables/T02_cleaning_log.csv/.md,
#          outputs/logs/02_inspection.txt (inspection evidence)
# Brief  : TASK.md §4, steps 2–3; decisions D-003, D-006, D-012, D-014
# =============================================================================
#
# The cleaning rules come from README §6. They were proposed with an AI
# assistant and approved by the owner; see docs/AI_USAGE.md (AI-003, AI-004).
# Every rule writes one row to the cleaning log (T02), even if it removes
# nothing, so the report shows that each check was actually run.
#
# All rules here are data-quality checks on the whole sample. They run before
# the train/test split (04_split.R) and never look at the target, except the
# physical-range check 0 < z < 1.

source(here::here("R", "00_setup.R"))

MAGNITUDES <- c("u", "g", "r", "i", "zmag")
ERRORS <- c("err_u", "err_g", "err_r", "err_i", "err_z")
COLOURS <- c("u_g", "g_r", "r_i", "i_z")

MAG_RANGE <- c(10, 30) # physically plausible apparent magnitudes
SENTINEL <- 9999 # SDSS marks missing photometry with -9999
MAD_K <- 5 # colour-outlier threshold: median ± 5·MAD

# --- Helpers -----------------------------------------------------------------

#' Append one rule to the cleaning log.
add_log <- function(log, step, rule, rows_before, rows_after, reason, details = "") {
  bind_rows(log, tibble::tibble(
    step = step, rule = rule,
    rows_before = rows_before, rows_after = rows_after,
    rows_removed = rows_before - rows_after,
    reason = reason, details = details
  ))
}

#' Colours = differences of magnitudes = flux ratios (spectral shape).
derive_colours <- function(df) {
  df |> mutate(
    u_g = u - g, # UV slope / Balmer-break region
    g_r = g - r, # 4000 Å break position: the main redshift signal
    r_i = r - i, # red continuum slope
    i_z = i - zmag # near-IR slope
  )
}

#' TRUE where x lies outside median ± k·MAD. R's mad() is scaled by 1.4826,
#' so 5·MAD is about 5σ for Gaussian data but is not pulled by outliers.
mad_outlier <- function(x, k = MAD_K) abs(x - median(x)) > k * mad(x)

# --- Step 1: read with explicit column types ---------------------------------

raw <- read_csv(PATHS$raw, col_types = RAW_COL_TYPES, comment = "#", progress = FALSE) |>
  janitor::clean_names()
stopifnot(identical(names(raw), RAW_COLUMNS))

df <- raw
log <- add_log(
  tibble::tibble(), 1, "Read raw CSV with explicit column types; clean_names()",
  nrow(raw), nrow(df), "Type safety (objid as text); consistent names"
)

# --- Step 2: inspect (structure, NAs, sentinels, duplicates, ranges) ---------

numeric_cols <- setdiff(names(df), "objid")
na_counts <- colSums(is.na(df))
sentinel_counts <- colSums(abs(df[numeric_cols]) >= SENTINEL, na.rm = TRUE)
colour_preview <- derive_colours(df)

inspection <- c(
  "INSPECTION OF data/raw/sdss_raw.csv",
  glue("Generated by R/02_inspect_clean.R on {Sys.Date()}"),
  "", "== Structure", capture.output(str(df, give.attr = FALSE)),
  "", "== Summary", capture.output(print(summary(df[numeric_cols]))),
  "", "== NA count per column", capture.output(print(na_counts)),
  "", glue("== Sentinel count per column (|x| >= {SENTINEL})"),
  capture.output(print(sentinel_counts)),
  "", "== Duplicates",
  glue("duplicate objid: {sum(duplicated(df$objid))}"),
  glue("fully duplicated rows: {sum(duplicated(df))}"),
  glue("objid lengths (digits): {paste(unique(nchar(df$objid)), collapse = ', ')}"),
  "", "== Colours (preview; derived formally in step 7)",
  capture.output(print(summary(colour_preview[COLOURS]))),
  "", glue("== Colour outliers beyond median ± {MAD_K}·MAD"),
  map_chr(COLOURS, \(v) {
    x <- colour_preview[[v]]
    glue("{v}: median {round(median(x), 3)}, MAD {round(mad(x), 3)}, ",
         "outliers {sum(mad_outlier(x))}")
  })
)
writeLines(inspection, file.path(PATHS$logs, "02_inspection.txt"))
cat(inspection, sep = "\n")

log <- add_log(
  log, 2, "Inspect structure, summary, NA, sentinels, duplicates",
  nrow(df), nrow(df), "Inspection evidence (outputs/logs/02_inspection.txt)",
  glue("NA cells: {sum(na_counts)}; sentinel cells: {sum(sentinel_counts)}")
)

# --- Step 3: remove duplicate objid ------------------------------------------

n_before <- nrow(df)
dups <- df$objid[duplicated(df$objid)]
df <- distinct(df, objid, .keep_all = TRUE)
log <- add_log(
  log, 3, "Remove duplicate objid", n_before, nrow(df),
  "One row per galaxy", paste(unique(dups), collapse = "; ")
)

# --- Step 4: remove NA or sentinel values ------------------------------------

n_before <- nrow(df)
bad <- df |>
  filter(if_any(all_of(numeric_cols), \(x) is.na(x) | abs(x) >= SENTINEL)) |>
  pull(objid)
df <- filter(df, !objid %in% bad)
log <- add_log(
  log, 4, glue("Remove rows with NA or sentinel (±{SENTINEL}) values"),
  n_before, nrow(df),
  "SDSS uses -9999 for missing photometry", paste(bad, collapse = "; ")
)

# --- Step 5: physical ranges -------------------------------------------------

n_before <- nrow(df)
out_of_range <- df |>
  filter(
    if_any(all_of(MAGNITUDES), \(m) m < MAG_RANGE[1] | m > MAG_RANGE[2]) |
      redshift <= 0 | redshift >= 1
  ) |>
  pull(objid)
df <- filter(df, !objid %in% out_of_range)
log <- add_log(
  log, 5, glue("Magnitudes in [{MAG_RANGE[1]}, {MAG_RANGE[2]}]; 0 < redshift < 1"),
  n_before, nrow(df), "Removes physically impossible values",
  paste(out_of_range, collapse = "; ")
)

# --- Step 6: colour outliers beyond median ± 5·MAD ---------------------------

n_before <- nrow(df)
flagged <- derive_colours(df) |>
  filter(if_any(all_of(COLOURS), mad_outlier))
df <- filter(df, !objid %in% flagged$objid)
log <- add_log(
  log, 6, glue("Remove colour outliers beyond median ± {MAD_K}·MAD (any colour)"),
  n_before, nrow(df), "Blended or bad photometry; MAD is robust to skew",
  paste(glue("{flagged$objid} (z = {round(flagged$redshift, 3)})"), collapse = "; ")
)

# --- Step 7: derive colours (features, D-006) --------------------------------

n_before <- nrow(df)
df <- derive_colours(df)
log <- add_log(
  log, 7, "Derive colours u_g, g_r, r_i, i_z", n_before, nrow(df),
  "Features (D-006): colours trace spectral shape, independent of brightness"
)

# --- Step 8: random sample to exactly N_TARGET (D-003) -----------------------

n_before <- nrow(df)
if (n_before > N_TARGET) {
  set.seed(SEED)
  df <- slice_sample(df, n = N_TARGET)
  sample_note <- glue("slice_sample(n = {N_TARGET}) with SEED = {SEED}")
} else {
  sample_note <- glue("Only {n_before} rows left: all kept (record in DECISIONS.md)")
  warning(sample_note, call. = FALSE)
}
log <- add_log(
  log, 8, glue("Random sample to {N_TARGET} rows"), n_before, nrow(df),
  "Brief: 30–100 observations (D-003)", sample_note
)

# --- Step 9: assert size, order columns, write -------------------------------

stopifnot(
  "Analysis dataset must have 30–100 rows (TASK.md C1)" =
    nrow(df) >= N_MIN && nrow(df) <= N_MAX,
  "Clean data must have no NA" = !anyNA(df),
  "objid must be unique" = !anyDuplicated(df$objid)
)

clean <- df |>
  arrange(objid) |>
  select(objid, all_of(MAGNITUDES), all_of(COLOURS), all_of(ERRORS),
         redshift, redshift_err, ra, dec)
write_csv(clean, PATHS$clean)

log <- add_log(
  log, 9, "Assert 30 ≤ n ≤ 100, no NA, unique objid; write sdss_clean.csv",
  nrow(df), nrow(clean), "Hard constraint C1",
  "data/processed/sdss_clean.csv"
)
save_table(log, "T02", "cleaning_log")

# --- Summary -----------------------------------------------------------------

message(glue(
  "\nCleaning: {nrow(raw)} raw rows -> {nrow(clean)} clean rows\n",
  "  removed by rules 3-6: {sum(log$rows_removed[log$step %in% 3:6])}\n",
  "  removed by sampling : {log$rows_removed[log$step == 8]}\n",
  "  redshift range      : {round(min(clean$redshift), 4)} to {round(max(clean$redshift), 4)}\n",
  "Wrote {PATHS$clean}",
  .trim = FALSE
))
