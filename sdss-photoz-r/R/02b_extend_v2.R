# =============================================================================
# 02b_extend_v2.R — Dataset version v2: add 20 new galaxies to the v1 sample
# Inputs : data/processed/v1/sdss_clean.csv (the 100 v1 galaxies),
#          data/raw/sdss_raw.csv (batch 1: frozen outlier reference),
#          data/raw/sdss_raw_batch2.csv (batch 2: 30 new galaxies)
# Outputs: data/processed/v2/sdss_clean.csv (120 rows = 100 v1 + 20 new),
#          data/processed/v2/new_galaxies.csv (the 20 new objids),
#          outputs/v2/tables/T02_cleaning_log.csv/.md,
#          outputs/v2/logs/02_inspection.txt
# Brief  : TASK.md §4, steps 2–3; decisions D-005, D-012, D-014, D-015, D-018
# =============================================================================
#
# Research design (D-018)
#   * The 100 v1 galaxies are kept unchanged, so v2 contains v1.
#   * Batch 2 passes exactly the same rules as batch 1 (utils_clean.R).
#   * The colour-outlier rule uses the batch-1 median and MAD, frozen. Re-
#     computing them on batch 1 + batch 2 could silently drop v1 galaxies,
#     and computing them on 30 rows alone would make the threshold noisy.
#   * Galaxies already in batch 1 are removed, so no galaxy can appear twice
#     (and none of the 20 new galaxies can be a v1 test galaxy).
#   * 20 of the survivors are drawn at random with SEED. The redshift is never
#     used to choose them, so the new galaxies are an unbiased extra sample
#     from the same population as v1.

source(here::here("R", "00_setup.R"))
source(here::here("R", "utils_clean.R"))

PATHS <- version_paths("v2")
for (dir in PATHS[c("processed", "tables", "logs")]) dir.create(dir, recursive = TRUE, showWarnings = FALSE)
V2 <- VERSIONS$v2
V1_PATHS <- version_paths("v1")

read_raw_batch <- function(path) {
  read_csv(path, col_types = RAW_COL_TYPES, comment = "#", progress = FALSE) |>
    janitor::clean_names()
}

v1_clean <- read_csv(V1_PATHS$clean, col_types = RAW_COL_TYPES, progress = FALSE)
stopifnot("v1 must be built first (Rscript R/02_inspect_clean.R)" =
            nrow(v1_clean) == VERSIONS$v1$n_total)

batch1 <- read_raw_batch(RAW_BATCHES$batch1$raw)
raw <- read_raw_batch(RAW_BATCHES$batch2$raw)
stopifnot(identical(names(raw), RAW_COLUMNS))

# Frozen outlier reference: batch 1 after rules 3–5, exactly the rows on which
# 02_inspect_clean.R computed its median and MAD.
batch1_ref_rows <- batch1 |>
  distinct(objid, .keep_all = TRUE) |>
  filter(!objid %in% bad_value_ids(batch1), !objid %in% out_of_range_ids(batch1))
reference <- colour_reference(batch1_ref_rows)
write_csv(reference, file.path(PATHS$tables, "cleaning_reference_batch1.csv"))

# --- Step 1: read ------------------------------------------------------------

df <- raw
log <- add_log(
  tibble::tibble(), 1, "Read batch-2 raw CSV with explicit column types; clean_names()",
  nrow(raw), nrow(df), "Type safety (objid as text); consistent names",
  "data/raw/sdss_raw_batch2.csv"
)

# --- Step 2: inspect ---------------------------------------------------------

numeric_cols <- setdiff(names(df), "objid")
na_counts <- colSums(is.na(df))
sentinel_counts <- colSums(abs(df[numeric_cols]) >= SENTINEL, na.rm = TRUE)
colour_preview <- derive_colours(df)

# Same population? Two-sample KS tests of batch 2 against batch 1 (raw)
ks_vars <- c("redshift", "r", "g_r", "u_g")
batch1_cols <- derive_colours(batch1)
ks_tab <- map_dfr(ks_vars, \(v) {
  k <- suppressWarnings(ks.test(colour_preview[[v]], batch1_cols[[v]]))
  tibble::tibble(variable = v, D = unname(k$statistic), p_value = k$p.value)
})

inspection <- c(
  "INSPECTION OF data/raw/sdss_raw_batch2.csv (dataset version v2, D-018)",
  glue("Generated by R/02b_extend_v2.R on {Sys.Date()}"),
  "", "== Structure", capture.output(str(df, give.attr = FALSE)),
  "", "== Summary", capture.output(print(summary(df[numeric_cols]))),
  "", "== NA count per column", capture.output(print(na_counts)),
  "", glue("== Sentinel count per column (|x| >= {SENTINEL})"),
  capture.output(print(sentinel_counts)),
  "", "== Duplicates",
  glue("duplicate objid within batch 2: {sum(duplicated(df$objid))}"),
  glue("objid also in batch 1: {sum(df$objid %in% batch1$objid)}"),
  glue("objid lengths (digits): {paste(unique(nchar(df$objid)), collapse = ', ')}"),
  "", "== Colours (preview)",
  capture.output(print(summary(colour_preview[COLOURS]))),
  "", glue("== Colour outliers beyond the FROZEN batch-1 median ± {MAD_K}·MAD"),
  map_chr(COLOURS, \(v) {
    ref <- reference[reference$colour == v, ]
    n_out <- sum(mad_outlier(colour_preview[[v]], centre = ref$median, scale = ref$mad))
    glue("{v}: batch-1 median {round(ref$median, 3)}, MAD {round(ref$mad, 3)}, outliers {n_out}")
  }),
  "", "== Same population as batch 1? (two-sample KS test, raw rows)",
  capture.output(print(as.data.frame(ks_tab), digits = 3))
)
writeLines(inspection, file.path(PATHS$logs, "02_inspection.txt"))
cat(inspection, sep = "\n")

log <- add_log(
  log, 2, "Inspect structure, summary, NA, sentinels, duplicates, KS vs batch 1",
  nrow(df), nrow(df), "Inspection evidence (outputs/v2/logs/02_inspection.txt)",
  glue("NA cells: {sum(na_counts)}; sentinel cells: {sum(sentinel_counts)}; ",
       "min KS p-value vs batch 1: {sprintf('%.2f', min(ks_tab$p_value))}")
)

# --- Step 3: duplicates within batch 2 and against batch 1 ------------------

n_before <- nrow(df)
dups <- unique(c(df$objid[duplicated(df$objid)], df$objid[df$objid %in% batch1$objid]))
df <- distinct(df, objid, .keep_all = TRUE) |> filter(!objid %in% batch1$objid)
log <- add_log(
  log, 3, "Remove duplicate objid (within batch 2 and already in batch 1)",
  n_before, nrow(df), "One row per galaxy; batches must not overlap",
  paste(dups, collapse = "; ")
)

# --- Step 4: NA or sentinel values -------------------------------------------

n_before <- nrow(df)
bad <- bad_value_ids(df)
df <- filter(df, !objid %in% bad)
log <- add_log(
  log, 4, glue("Remove rows with NA or sentinel (±{SENTINEL}) values"),
  n_before, nrow(df), "SDSS uses -9999 for missing photometry", paste(bad, collapse = "; ")
)

# --- Step 5: physical ranges -------------------------------------------------

n_before <- nrow(df)
out_of_range <- out_of_range_ids(df)
df <- filter(df, !objid %in% out_of_range)
log <- add_log(
  log, 5, glue("Magnitudes in [{MAG_RANGE[1]}, {MAG_RANGE[2]}]; 0 < redshift < 1"),
  n_before, nrow(df), "Removes physically impossible values",
  paste(out_of_range, collapse = "; ")
)

# --- Step 6: colour outliers against the frozen batch-1 reference -----------

n_before <- nrow(df)
flagged <- colour_outliers(df, reference)
df <- filter(df, !objid %in% flagged$objid)
log <- add_log(
  log, 6, glue("Remove colour outliers beyond batch-1 median ± {MAD_K}·MAD (frozen)"),
  n_before, nrow(df), "Same rule and threshold as v1; blended or bad photometry",
  paste(glue("{flagged$objid} (z = {round(flagged$redshift, 3)})"), collapse = "; ")
)

# --- Step 7: colours ---------------------------------------------------------

n_before <- nrow(df)
df <- derive_colours(df)
log <- add_log(
  log, 7, "Derive colours u_g, g_r, r_i, i_z", n_before, nrow(df),
  "Features (D-006): colours trace spectral shape, independent of brightness"
)

# --- Step 8: random sample of exactly 20 new galaxies -----------------------

n_before <- nrow(df)
if (n_before < V2$n_new) {
  stop(glue("Only {n_before} batch-2 galaxies survived cleaning; {V2$n_new} are needed. ",
            "Record a new decision before pulling more data."), call. = FALSE)
}
set.seed(SEED)
new <- slice_sample(df, n = V2$n_new)
log <- add_log(
  log, 8, glue("Random sample to {V2$n_new} new galaxies"), n_before, nrow(new),
  "D-018: v2 = v1 (100) + 20 new galaxies",
  glue("slice_sample(n = {V2$n_new}) with SEED = {SEED}")
)

# --- Step 9: append to v1, assert, write -------------------------------------

clean <- bind_rows(v1_clean, order_clean_columns(new)) |> order_clean_columns()
stopifnot(
  "v2 must have 120 rows (D-018)" = nrow(clean) == V2$n_total,
  "v2 must contain every v1 galaxy" = all(v1_clean$objid %in% clean$objid),
  "Clean data must have no NA" = !anyNA(clean),
  "objid must be unique" = !anyDuplicated(clean$objid)
)
write_csv(clean, PATHS$clean)
write_csv(tibble::tibble(objid = sort(new$objid)), file.path(PATHS$processed, "new_galaxies.csv"))

log <- add_log(
  log, 9, "Append to the 100 v1 galaxies; assert n = 120, no NA, unique objid",
  nrow(new), nrow(clean), "D-018 (owner-approved extension beyond the brief's 100)",
  "data/processed/v2/sdss_clean.csv"
)
save_table(log, "T02", "cleaning_log")

message(glue(
  "\nv2 extension: {nrow(raw)} batch-2 rows -> {n_before} clean -> {nrow(new)} sampled\n",
  "  new galaxies z  : {round(min(new$redshift), 4)} to {round(max(new$redshift), 4)}\n",
  "  v2 dataset      : {nrow(clean)} galaxies\n",
  "Wrote {PATHS$clean}",
  .trim = FALSE
))
